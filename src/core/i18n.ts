const BUNDLES: Record<LangCode, Strings> = { en: EN, tr: TR, de: DE, fr: FR };

export function currentLanguage(): LangCode {
    const configured = configuredLanguage();
    if (configured !== 'auto' && configured in BUNDLES) { return configured as LangCode; }
    const locale = vscode.env.language.toLowerCase().split('-')[0];
    return (locale in BUNDLES ? locale : 'en') as LangCode;
}

/** Webview'e gonderilen tam sozluk. Eksik anahtar Ingilizceye duser. */
export function bundle(): Strings {
    return { ...EN, ...BUNDLES[currentLanguage()] };
}

export function t(key: string, ...args: (string | number)[]): string {
    return format(bundle()[key] ?? key, args);
}

export function format(template: string, args: (string | number)[]): string {
    return template.replace(/\{(\d+)\}/g, (match, index) => {
        const value = args[Number(index)];
        return value === undefined ? match : String(value);
    });
}
